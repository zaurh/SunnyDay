// The WeatherAPI key is read from local.properties (WEATHER_API_KEY=...) or the
// WEATHER_API_KEY environment variable so it is never committed to source control.
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use(::load)
}
val weatherApiKey: String = localProperties.getProperty("WEATHER_API_KEY")
    ?: System.getenv("WEATHER_API_KEY")
    ?: ""

// Release signing is read from keystore.properties (git-ignored). Without it, release builds are unsigned.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use(::load)
}

